CREATE TABLE `stj_cliente_eventos` (
  `cev_id` BIGINT NOT NULL AUTO_INCREMENT,
  `cev_event_uuid` CHAR(36) NOT NULL,
  `cev_visitante_id` BIGINT NOT NULL,
  `cev_usu_id` BIGINT NULL,
  `cev_pais_id` BIGINT NULL,
  `cev_producto_id` BIGINT NULL,
  `cev_pedido_id` BIGINT NULL,
  `cev_carrito_id` BIGINT NULL,
  `cev_tipo` VARCHAR(32) NOT NULL,
  `cev_cantidad` INT UNSIGNED NULL,
  `cev_valor` DECIMAL(12,2) NULL,
  `cev_moneda` CHAR(3) NULL,
  `cev_origen` VARCHAR(20) NOT NULL DEFAULT 'WEB',
  `cev_ocurrido_en` DATETIME(6) NOT NULL,
  `cev_recibido_en` DATETIME(6) NOT NULL,
  `cev_metadata` JSON NULL,
  PRIMARY KEY (`cev_id`),
  UNIQUE KEY `uq_cev_event_uuid` (`cev_event_uuid`),
  KEY `idx_cev_visitante_fecha` (`cev_visitante_id`, `cev_ocurrido_en`),
  KEY `idx_cev_usuario_fecha` (`cev_usu_id`, `cev_ocurrido_en`),
