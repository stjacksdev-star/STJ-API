  KEY `idx_cev_pais_tipo_fecha` (`cev_pais_id`, `cev_tipo`, `cev_ocurrido_en`),
  KEY `idx_cev_pedido` (`cev_pedido_id`),
  KEY `idx_cev_carrito` (`cev_carrito_id`),
  CONSTRAINT `fk_cev_visitante` FOREIGN KEY (`cev_visitante_id`) REFERENCES `stj_visitantes` (`vis_id`),
  CONSTRAINT `fk_cev_usuario` FOREIGN KEY (`cev_usu_id`) REFERENCES `stj_usuarios` (`usu_id`),
  CONSTRAINT `fk_cev_pais` FOREIGN KEY (`cev_pais_id`) REFERENCES `stj_paises` (`pai_id`),
  CONSTRAINT `fk_cev_producto` FOREIGN KEY (`cev_producto_id`) REFERENCES `stj_productos` (`pro_id`),
  CONSTRAINT `fk_cev_pedido` FOREIGN KEY (`cev_pedido_id`) REFERENCES `stj_pedidos` (`ped_id`),
  CONSTRAINT `fk_cev_carrito` FOREIGN KEY (`cev_carrito_id`) REFERENCES `stj_carritos` (`car_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
